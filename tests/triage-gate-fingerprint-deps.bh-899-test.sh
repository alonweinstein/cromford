#!/bin/bash
# tests/triage-gate-fingerprint-deps.bh-899-test.sh — BH-899 (BH-815.0): the
# in-app fingerprint carries the dependency fields when, and ONLY when, the
# board serves them.
#
# The board contract grows four ticket fields — `parentId`, `dependsOn`,
# `children` and a derived `blocked` boolean (docs/BOARD-API-CONTRACT.md,
# "Dependencies"). There is no version negotiation in that contract, so ABSENCE
# IS THE SIGNAL and the detection is per ticket object on the TYPE of `blocked`:
# only a JSON boolean counts. `null`, the string `"true"` and a missing key are
# all "this board has not adopted dependencies".
#
# TWO PROPERTIES, and the second one carries the weight:
#   1. a board that serves the fields gets a fingerprint that CARRIES
#      {key, blocked, parentId, dependsOn:[ids]}, so a blocker landing flips
#      `blocked` and the real bin/gate-diff.sh names the released child;
#   2. a board that does not gets a fingerprint whose BYTES are identical to
#      tests/fixtures/triage-gate-dependencies/oldboard-fingerprint.json, which
#      was generated by running the UNEDITED bin/triage-gate.sh against the same
#      old-board listing. Every in-app project on the fleet is that board today:
#      if this compare goes red, one release re-fingerprints every board on the
#      fleet and every project buys a full session for nothing.
#
# REGENERATING THE ORACLE. Only ever against a checkout of bin/triage-gate.sh
# that predates this ticket, from the repo root:
#
#   S=$(mktemp); git show origin/main:bin/triage-gate.sh > "$S"
#   HARNESS_TEST_SANDBOX=1 TRIAGE_GATE_UNDER_TEST="$S" bash tests/triage-gate-fingerprint-deps.bh-899-test.sh --dump-oldboard
#
# Add --stdout to print the bytes instead of writing the fixture.
#
# Drives the REAL bin/triage-gate.sh and bin/gate-diff.sh against a scratch
# $HARNESS with a stubbed curl. No network, no model, no clock reads.
# Run from anywhere: tests/triage-gate-fingerprint-deps.bh-899-test.sh (exit 0 = all pass)
set -uo pipefail
. "$(dirname "$0")/lib/scratch.sh" || exit 1

DIR=$(cd "$(dirname "$0")/.." && pwd)
FIX="$DIR/tests/fixtures/triage-gate-dependencies"
ORACLE="$FIX/oldboard-fingerprint.json"
GATE_SRC="${TRIAGE_GATE_UNDER_TEST:-$DIR/bin/triage-gate.sh}"

DUMP=0; DUMP_STDOUT=0
for a in "$@"; do
  case "$a" in
    --dump-oldboard) DUMP=1 ;;
    --stdout)        DUMP_STDOUT=1 ;;
    *) echo "triage-gate-fingerprint-deps: unknown argument $a" >&2; exit 2 ;;
  esac
done

PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL: $1"; }

command -v jq >/dev/null 2>&1      || { echo "triage-gate-fingerprint-deps: jq missing, cannot run" >&2; exit 1; }
command -v python3 >/dev/null 2>&1 || { echo "triage-gate-fingerprint-deps: python3 missing, cannot run (gate-diff.sh is python)" >&2; exit 1; }
[ -r "$GATE_SRC" ]                 || { echo "triage-gate-fingerprint-deps: no script under test at $GATE_SRC" >&2; exit 1; }

mkdir -p "$T/bin" "$T/env" "$T/state" "$T/logs" "$T/flags" "$T/fixture"

# The scripts under test, run against the scratch harness.
cp "$GATE_SRC"           "$T/bin/triage-gate.sh"
# BH-1955: the generic arm resolves its token through these two libs.
mkdir -p "$T/bin/lib" && cp "$DIR/bin/lib/board-creds.sh" "$DIR/bin/lib/internal-token.sh" "$T/bin/lib/"
cp "$DIR/bin/board-fetch.sh" "$T/bin/board-fetch.sh"
cp "$DIR/bin/gate-diff.sh"   "$T/bin/gate-diff.sh"
chmod +x "$T/bin/triage-gate.sh" "$T/bin/board-fetch.sh" "$T/bin/gate-diff.sh"

# fleet.conf stand-in: x-os is an in-app product board, ghproj is GitHub Issues.
cat > "$T/bin/fleet-conf.sh" <<'EOC'
#!/bin/bash
case "${1:-}" in
  x-os)
    case "${2:-}" in
      repo) echo "" ;;
      board_prefix|*) echo "/api/board" ;;
    esac ;;
  ghproj)
    case "${2:-}" in
      repo) echo "example-org/ghproj" ;;
      board_prefix|*) echo "-" ;;
    esac ;;
  *) echo "" ;;
esac
EOC
chmod +x "$T/bin/fleet-conf.sh"

# Board credentials discovered by suffix (the generic in-app arm of the gate,
# bin/triage-gate.sh:73-76).
cat > "$T/env/x-os.env" <<'EOC'
XOS_API_BASE=https://board.example
XOS_INTERNAL_API_TOKEN=tok
EOC

# curl stand-in (the mkcurl() pattern of tests/sweep-stale-builds-test.sh:37).
# Every response is a file under $T/fixture, so a case swaps the board by
# swapping one file. -f is what fetch_fingerprint passes, so a missing file is
# a nonzero exit, not an empty 200.
cat > "$T/bin/curl" <<EOC
#!/bin/bash
OUT=""; URL=""
while [ \$# -gt 0 ]; do
  case "\$1" in
    -o) shift; OUT="\${1:-}" ;;
    -H) shift; : ;;
    -m) shift; : ;;
    -w) shift; : ;;
    -*) : ;;
    *) URL="\$1" ;;
  esac
  shift || true
done
F=""
case "\$URL" in
  */boards/*/tickets) F="$T/fixture/tickets.json" ;;
  */boards)           F="$T/fixture/boards.json" ;;
  */tickets/*)        F="$T/fixture/ticket-\${URL##*/tickets/}.json" ;;
esac
[ -n "\$F" ] && [ -f "\$F" ] || exit 22
if [ -n "\$OUT" ]; then cat "\$F" > "\$OUT"; else cat "\$F"; fi
exit 0
EOC
chmod +x "$T/bin/curl"

# gh is never legitimate on an in-app board; make a call loud AND recorded.
cat > "$T/bin/gh" <<EOC
#!/bin/bash
echo gh-called-unexpectedly >&2
touch "$T/gh-called"
exit 99
EOC
chmod +x "$T/bin/gh"

export HARNESS="$T"
export PATH="$T/bin:$PATH"

FP="$T/state/x-os.gate.json"
KEYMAP="$T/state/x-os.keymap.json"

seed() { # seed <boards-fixture> <tickets-fixture> -> $FP
  cp "$FIX/$1" "$T/fixture/boards.json"
  cp "$FIX/$2" "$T/fixture/tickets.json"
  rm -f "$FP" "$T/state/x-os.gate.pending" "$T/state/x-os.gate-meta" "$KEYMAP"
  bash "$T/bin/triage-gate.sh" x-os --seed >/dev/null 2>&1
}

# ── regeneration mode ────────────────────────────────────────────────────────
if [ "$DUMP" = 1 ]; then
  seed boards-old.json tickets-old.json
  [ -s "$FP" ] || { echo "triage-gate-fingerprint-deps: --dump-oldboard produced no fingerprint" >&2; exit 1; }
  if [ "$DUMP_STDOUT" = 1 ]; then
    cat "$FP"
  else
    cp "$FP" "$ORACLE"
    echo "triage-gate-fingerprint-deps: wrote $ORACLE from $GATE_SRC"
  fi
  exit 0
fi

# ── case 1: an adopted board carries the four extra keys, per ticket ─────────
seed boards-cap.json tickets-cap.json
if [ -s "$FP" ]; then ok; else bad "--seed wrote no fingerprint for the capability board"; fi

CHILD=$(jq -c '.b1[] | select(.id == 1825)' "$FP" 2>/dev/null)
[ "$(jq -r '.blocked'   <<<"$CHILD" 2>/dev/null)" = "true" ]      && ok || bad "1825 must fingerprint blocked:true, got: $CHILD"
[ "$(jq -r '.parentId'  <<<"$CHILD" 2>/dev/null)" = "1830" ]      && ok || bad "1825 must fingerprint parentId 1830, got: $CHILD"
[ "$(jq -c '.dependsOn' <<<"$CHILD" 2>/dev/null)" = '[1800]' ]    && ok || bad "1825 must fingerprint dependsOn as a list of IDS, got: $CHILD"
[ "$(jq -r '.key'       <<<"$CHILD" 2>/dev/null)" = "TK-1825" ]   && ok || bad "1825 must fingerprint key TK-1825, got: $CHILD"
# …and the original seven fields are all still there, unmoved.
[ "$(jq -r '[.id,.status,.waitingOn,.triageVerdict,.commentCount,.lastActivityAt,.title] | @csv' <<<"$CHILD" 2>/dev/null)" \
  = '1825,"todo","team","ready",1,"2026-09-18T05:01:00Z","Rep-facing fee screen"' ] && ok \
  || bad "the original seven fingerprint fields must survive on 1825, got: $CHILD"

# blocked:false is NOT absence. This is the row jq's `//` would get wrong.
BLOCKER=$(jq -c '.b1[] | select(.id == 1800)' "$FP" 2>/dev/null)
[ "$(jq -r '.blocked'   <<<"$BLOCKER" 2>/dev/null)" = "false" ] && ok || bad "1800 (blocked:false) must still carry blocked, got: $BLOCKER"
[ "$(jq -r 'has("parentId") and .parentId == null' <<<"$BLOCKER" 2>/dev/null)" = "true" ] && ok || bad "1800 must carry parentId as a present null, got: $BLOCKER"
[ "$(jq -c '.dependsOn' <<<"$BLOCKER" 2>/dev/null)" = '[]' ]    && ok || bad "1800 must carry dependsOn:[], got: $BLOCKER"

# THE ADVERSARIAL NEGATIVE: a string "true" is not a boolean, so 1840's row must
# carry NONE of the four keys even though it sits on an adopted board.
STR=$(jq -c '.b1[] | select(.id == 1840)' "$FP" 2>/dev/null)
if [ "$(jq -r '[has("blocked"),has("key"),has("parentId"),has("dependsOn")] | any' <<<"$STR" 2>/dev/null)" = "false" ]; then
  ok
else
  bad "a row whose blocked is the STRING \"true\" must project none of the four keys, got: $STR"
fi

# the id<->key map the release line resolves dependency ids through
[ "$(jq -r '."1825"' "$KEYMAP" 2>/dev/null)" = "TK-1825" ] && ok || bad "keymap must resolve 1825 -> TK-1825"
[ "$(jq -r '."TK-1825"' "$KEYMAP" 2>/dev/null)" = "1825" ] && ok || bad "keymap must resolve TK-1825 -> 1825"

# ── case 2: THE REGRESSION GUARD — an un-adopted board is byte-identical ─────
if [ ! -f "$ORACLE" ]; then
  bad "the pre-change oracle $ORACLE is missing — a missing oracle is a failure, never a skip"
else
  seed boards-old.json tickets-old.json
  if cmp -s "$FP" "$ORACLE"; then ok; else
    bad "old-board fingerprint bytes changed: $(diff <(jq -S . "$ORACLE" 2>/dev/null) <(jq -S . "$FP" 2>/dev/null) | head -20)"
  fi

  # ── case 3: …and a board serving the keys as JSON null is the same bytes ──
  seed boards-cap.json tickets-null.json
  if cmp -s "$FP" "$ORACLE"; then ok; else
    bad "blocked:null fingerprint must equal the old-board bytes: $(diff <(jq -S . "$ORACLE" 2>/dev/null) <(jq -S . "$FP" 2>/dev/null) | head -20)"
  fi
fi

# ── case 4: a blocker landing names the released child, through gate-diff ────
# The real bin/gate-diff.sh, not a restatement of it.
seed boards-cap.json tickets-cap.json
cp "$FP" "$T/before"
cp "$FIX/tickets-cap-after.json" "$T/fixture/tickets.json"
bash "$T/bin/triage-gate.sh" x-os --pending >/dev/null 2>&1
cp "$T/before" "$FP"
DIFF=$(bash "$T/bin/gate-diff.sh" x-os 2>/dev/null); DRC=$?
[ "$DRC" -eq 0 ] && ok || bad "gate-diff.sh over the two dependency fingerprints must exit 0, got rc=$DRC"
[ "$(grep -cE '^board [^:]+: CHANGED 1825 ' <<<"$DIFF")" = "1" ] && ok \
  || bad "the released child must produce exactly one CHANGED 1825 line: $DIFF"
[ "$(grep -c ' 1826 ' <<<"$DIFF")" = "0" ] && ok \
  || bad "the sibling 1826 did not move and must not appear in the diff: $DIFF"
# A dependency's own status move is what the release lane reads off the blocker.
[ "$(grep -cE '^board [^:]+: CHANGED 1800 .*status: review -> done' <<<"$DIFF")" = "1" ] && ok \
  || bad "the blocker's status move must be named once: $DIFF"

# The in-app arm must never reach for gh.
[ -e "$T/gh-called" ] && bad "the in-app fingerprint arm called gh" || ok

echo "triage-gate-fingerprint-deps: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ]
