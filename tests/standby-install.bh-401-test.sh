#!/bin/bash
# tests/standby-install.bh-401-test.sh — bin/standby-install.sh and the
# fleet.conf `# @standby` directive (#401, slice BH-1924).
#
# A standby box runs every hub lane behind `hub-lease.sh check && `, so the
# lanes stay inert until the hub's lease lapses. The shapes worth pinning are
# the ones that would make a standby act as the hub while the hub is alive: a
# renew line that is not gated (the standby takes the lease on its own), a
# watchdog ping that is not dropped (the standby pings as the hub), a lane the
# box already runs that is not dropped (it runs twice), and a gate that lands
# twice or not at all.
#
# Run: HARNESS_TEST_SANDBOX=1 bash tests/standby-install.bh-401-test.sh
set -uo pipefail
. "$(dirname "$0")/lib/scratch.sh" || exit 1
REPO=$(cd "$(dirname "$0")/.." && pwd)
SI="$REPO/bin/standby-install.sh"
FC="$REPO/bin/fleet-conf.sh"
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL: $1"; }
check() { if [ "$2" = "$3" ]; then ok; else bad "$1: want [$3] got [$2]"; fi; }

G='/root/harness/bin/hub-lease.sh check && '
STREAM='10,25,40,55 * * * * root /root/harness/bin/hub-lease.sh check || /root/harness/bin/state-restore.sh hub latest --apply --standby >> /root/harness/logs/standby-stream.log 2>&1'
VERIFY='*/5 * * * * root /root/harness/bin/hub-lease.sh check || /root/harness/bin/standby-verify.sh >> /root/harness/logs/standby-verify.log 2>&1'

# ---- sandbox -----------------------------------------------------------------
export HARNESS="$T/h"
mkdir -p "$HARNESS/env" "$HARNESS/state" "$HARNESS/logs" "$T/stub" "$T/cron.d"
: > "$HARNESS/env/global.env"          # keeps /etc/harness/env out of reach
printf 'small\n' > "$HARNESS/state/box-id"
unset HUB_BOX_NAME HARNESS_ENV_DIR
export BOX_NAME=box-small
export BACKUP_S3_ENDPOINT=https://s3.example BACKUP_S3_ACCESS_KEY_ID=AKIDUMMY
export BACKUP_S3_SECRET_ACCESS_KEY=sekrit-value-never-printed
printf 'AGE-SECRET-KEY-DUMMY\n' > "$T/age.key"
export BACKUP_AGE_IDENTITY_FILE="$T/age.key"
printf '#!/bin/sh\nexit "${PGREP_RC:-0}"\n' > "$T/stub/pgrep"; chmod +x "$T/stub/pgrep"
export PATH="$T/stub:$PATH"
CRON="$T/cron.d/harness-standby"

cp "$REPO/fleet.conf" "$T/fleet.conf"
grep -v '@standby' "$REPO/fleet.conf" > "$T/fleet.noconf"

cat > "$T/hub.cron" <<'EOF'
SHELL=/bin/bash
# a comment that mentions watchdog-ping.sh, dropped as a comment

@reboot /root/harness/bin/boot.sh
PATH=/usr/bin:/bin
*/5 * * * * /root/harness/bin/watchdog-ping.sh box-hub
*/10 * * * * curl -fsS https://hc.example/api/ping/abc >/dev/null
* * * * * /root/harness/bin/hub-lease.sh renew >/dev/null 2>&1
*/2 * * * * /root/harness/bin/lane-a.sh
*/3 * * * * /root/harness/bin/lane-b.sh
*/4 * * * * /root/harness/bin/alert-flush.sh
*/6  *  * * *   /root/harness/bin/lane-c.sh >/dev/null 2>&1
*/7 * * * * /root/harness/bin/hub-lease.sh check && /root/harness/bin/gated-a.sh
*/8 * * * * /root/harness/bin/hub-lease.sh check && /root/harness/bin/gated-b.sh
*/9 * * * * /root/harness/bin/shared.sh
*/11 * * * * /root/harness/bin/shared.sh --extra
MAILTO=""
EOF
cat > "$T/own.cron" <<'EOF'
PATH=/root/harness/bin:/usr/bin:/bin
@reboot /root/harness/bin/own-boot.sh
*/5 * * * * /root/harness/bin/watchdog-ping.sh box-small
3 * * * * /root/harness/bin/hub-lease.sh check && /root/harness/bin/shared.sh
EOF
INJ=(--hub-crontab "$T/hub.cron" --own-crontab "$T/own.cron")

sched() { grep -vE '^#|^[A-Za-z_][A-Za-z0-9_]*=' "$1"; }

# ---- S1: dry run, fixture counts, drops, prefix once, header -------------------
OUT=$("$SI" box-small --root "$REPO" --cron-file "$CRON" "${INJ[@]}" 2>"$T/err"); RC=$?
check "S1 rc" "$RC" 0
printf '%s\n' "$OUT" > "$T/s1.out"
check "S1 header" "$(head -1 "$T/s1.out")" \
  "# generated by bin/standby-install.sh for box-small — standby of box-hub (hub). Do not edit; re-run the installer."
# The stream (last) and the verify line (BH-2640) are the installer's own
# ungated lines; everything else is the gated hub lane list below.
sched "$T/s1.out" | sed '$d' | grep -vF '/bin/standby-verify.sh ' > "$T/s1.sched"
cat > "$T/s1.want" <<EOF
* * * * * root ${G}/root/harness/bin/hub-lease.sh renew >/dev/null 2>&1
*/2 * * * * root ${G}/root/harness/bin/lane-a.sh
*/3 * * * * root ${G}/root/harness/bin/lane-b.sh
*/4 * * * * root ${G}/root/harness/bin/alert-flush.sh
*/6 * * * * root ${G}/root/harness/bin/lane-c.sh >/dev/null 2>&1
*/7 * * * * root ${G}/root/harness/bin/gated-a.sh
*/8 * * * * root ${G}/root/harness/bin/gated-b.sh
*/11 * * * * root ${G}/root/harness/bin/shared.sh --extra
EOF
if diff "$T/s1.want" "$T/s1.sched" >"$T/s1.diff"; then ok; else bad "S1 schedule lines differ:"; cat "$T/s1.diff"; fi
check "S1 count" "$(wc -l < "$T/s1.sched")" 8
check "S1 every line gated" "$(grep -cvE '^[^ ]+ [^ ]+ [^ ]+ [^ ]+ [^ ]+ root /root/harness/bin/hub-lease\.sh check && ' "$T/s1.sched")" 0
check "S1 no double prefix" "$(grep -c 'check && .*check && ' "$T/s1.out")" 0
check "S1 no watchdog ping" "$(grep -c 'watchdog-ping' "$T/s1.out")" 0
check "S1 no /api/ping/" "$(grep -c '/api/ping/' "$T/s1.out")" 0
check "S1 no @reboot" "$(grep -c '@reboot' "$T/s1.out")" 0
check "S1 byte-equal own lane dropped" "$(grep -cE ' /root/harness/bin/shared\.sh$' "$T/s1.out")" 0
check "S1 alert-flush survives" "$(grep -c 'alert-flush.sh' "$T/s1.out")" 1
[ -e "$CRON" ] && bad "S1 dry run wrote $CRON" || ok
[ -e "$HARNESS/state/standby-of" ] && bad "S1 dry run wrote state/standby-of" || ok
check "S1 ends in newline" "$("$SI" box-small --root "$REPO" --cron-file "$CRON" "${INJ[@]}" 2>/dev/null | tail -c1 | od -An -c | tr -d ' ')" '\n'

# ---- S2: renew gated, env lines kept in hub order ----------------------------
check "S2 renew" "$(grep 'hub-lease.sh renew' "$T/s1.out")" \
  "* * * * * root /root/harness/bin/hub-lease.sh check && /root/harness/bin/hub-lease.sh renew >/dev/null 2>&1"
check "S2 env order" "$(grep -E '^[A-Za-z_][A-Za-z0-9_]*=' "$T/s1.out" | tr '\n' '|')" 'SHELL=/bin/bash|PATH=/usr/bin:/bin|MAILTO=""|'
check "S2 MAILTO keeps its position" "$(grep -n 'MAILTO' "$T/s1.out" | cut -d: -f1)" "$(($(grep -n 'shared.sh --extra' "$T/s1.out" | cut -d: -f1)+1))"
check "S2 last line is the stream" "$(tail -1 "$T/s1.out")" "$STREAM"
check "S2 second-to-last line is the verify line" "$(tail -2 "$T/s1.out" | head -1)" "$VERIFY"
check "S2 only the stream and the verify line are ungated" "$(sched "$T/s1.out" | grep -cv "root ${G}")" 2

# ---- S8: refusals --------------------------------------------------------------
"$SI" box-nope --root "$REPO" --cron-file "$CRON" "${INJ[@]}" >/dev/null 2>"$T/err"; RC=$?
check "S8a rc" "$RC" 1
grep -q 'not registered' "$T/err" && ok || bad "S8a stderr: $(cat "$T/err")"
"$SI" box-hub --root "$REPO" --cron-file "$CRON" "${INJ[@]}" >/dev/null 2>"$T/err"; RC=$?
check "S8b rc (box is hub)" "$RC" 1
grep -q 'is the hub' "$T/err" && ok || bad "S8b stderr: $(cat "$T/err")"
check "S8 dry refusals write no ALERTS" "$(cat "$HARNESS/logs/ALERTS.log" 2>/dev/null | wc -l)" 0
BOX_NAME=box-project-4-1 "$SI" box-small --apply --root "$REPO" --cron-file "$CRON" "${INJ[@]}" >/dev/null 2>"$T/err"; RC=$?
check "S8c rc (wrong box)" "$RC" 1
grep -q 'this box is box-project-4-1, not box-small' "$T/err" && ok || bad "S8c stderr: $(cat "$T/err")"
check "S8c one ALERTS line" "$(grep -c '\[standby-install\] REFUSED box-small' "$HARNESS/logs/ALERTS.log" 2>/dev/null)" 1
[ -e "$CRON" ] && bad "S8 a refusal wrote $CRON" || ok
[ -e "$HARNESS/state/standby-of" ] && bad "S8 a refusal wrote standby-of" || ok

# S8b: env and cron refusals, secrets never echoed
BACKUP_S3_ENDPOINT= "$SI" box-small --root "$REPO" --cron-file "$CRON" "${INJ[@]}" >/dev/null 2>"$T/err"; RC=$?
check "S8b env rc" "$RC" 1
grep -q 'missing: BACKUP_S3_ENDPOINT' "$T/err" && ok || bad "S8b env stderr: $(cat "$T/err")"
BACKUP_AGE_IDENTITY_FILE="$T/nope.key" BACKUP_S3_SECRET_ACCESS_KEY= "$SI" box-small --root "$REPO" --cron-file "$CRON" "${INJ[@]}" >/dev/null 2>"$T/err"; RC=$?
check "S8b two missing rc" "$RC" 1
grep -q 'missing: BACKUP_S3_SECRET_ACCESS_KEY BACKUP_AGE_IDENTITY_FILE' "$T/err" && ok || bad "S8b two missing stderr: $(cat "$T/err")"
grep -rq 'sekrit-value\|AKIDUMMY\|s3.example' "$T/err" "$HARNESS/logs" && bad "S8b a secret value was printed" || ok
PGREP_RC=1 "$SI" box-small --apply --root "$REPO" --cron-file "$CRON" "${INJ[@]}" >/dev/null 2>"$T/err"; RC=$?
check "S8b cron rc" "$RC" 1
grep -q 'cron not running' "$T/err" && ok || bad "S8b cron stderr: $(cat "$T/err")"
check "S8b cron ALERTS line" "$(grep -c 'REFUSED box-small: cron not running' "$HARNESS/logs/ALERTS.log")" 1
"$SI" box-small --root "$REPO" --cron-file "$T/no-such-dir/harness-standby" "${INJ[@]}" >/dev/null 2>"$T/err"; RC=$?
check "S8b no cron.d rc" "$RC" 1
grep -q 'no cron.d dir' "$T/err" && ok || bad "S8b cron.d stderr: $(cat "$T/err")"
[ -e "$CRON" ] && bad "S8b a refusal wrote $CRON" || ok

# usage errors
"$SI" box-small --bogus >/dev/null 2>&1; check "unknown flag rc" "$?" 2
"$SI" box-small --hub-crontab "$T/hub.cron" >/dev/null 2>&1; check "half injection rc" "$?" 2

# ---- S9: --apply installs atomically ------------------------------------------
"$SI" box-small --apply --root "$REPO" --cron-file "$CRON" "${INJ[@]}" >/dev/null 2>"$T/err"; RC=$?
check "S9 rc" "$RC" 0
check "S9 mode" "$(stat -c %a "$CRON" 2>/dev/null)" 644
check "S9 last line" "$(tail -1 "$CRON")" "$STREAM"
check "S9 standby-of" "$(cat "$HARNESS/state/standby-of" 2>/dev/null)" "box-hub hub"
check "S9 installed == dry run" "$(cat "$CRON")" "$(cat "$T/s1.out")"
check "S9 no tmp left" "$(find "$T/cron.d" "$HARNESS/state" -name '.*' -type f | wc -l)" 0

# ---- S10: --conf is idempotent --------------------------------------------------
grep -v '^# @standby ' "$REPO/fleet.conf" > "$T/fleet.s10"
"$SI" box-small --root "$REPO" --cron-file "$CRON" --conf "$T/fleet.s10" "${INJ[@]}" >/dev/null 2>&1
check "S10 first run appends" "$(grep -c '^# @standby box-small box-hub hub$' "$T/fleet.s10")" 1
sed -i 's/^# @standby box-small .*/# @standby box-small old-hub old/' "$T/fleet.s10"
cp "$T/fleet.s10" "$T/fleet.s10.before"
"$SI" box-small --root "$REPO" --cron-file "$CRON" --conf "$T/fleet.s10" "${INJ[@]}" >/dev/null 2>&1
"$SI" box-small --root "$REPO" --cron-file "$CRON" --conf "$T/fleet.s10" "${INJ[@]}" >/dev/null 2>&1
check "S10 exactly one line" "$(grep -c '^# @standby box-small box-hub hub$' "$T/fleet.s10")" 1
check "S10 total directives" "$(grep -c '^# @standby ' "$T/fleet.s10")" 1
check "S10 replaced in place" "$(diff "$T/fleet.s10.before" "$T/fleet.s10" | grep -c '^[<>]')" 2
check "S10 rows untouched" "$(FLEET_CONF="$T/fleet.s10" "$FC" --projects)" "$(FLEET_CONF="$T/fleet.noconf" "$FC" --projects)"

# ---- S11: fleet-conf.sh --standby / --standby-of --------------------------------
check "S11 --standby" "$(FLEET_CONF="$T/fleet.conf" "$FC" --standby)" "box-small box-hub hub"
check "S11 --standby-of" "$(FLEET_CONF="$T/fleet.conf" "$FC" --standby-of box-small)" "box-hub hub"
OUT=$(FLEET_CONF="$T/fleet.conf" "$FC" --standby-of box-project-4-1); RC=$?
check "S11 --standby-of unknown rc" "$RC" 1
check "S11 --standby-of unknown stdout" "$OUT" ""
check "S11 --projects unchanged" "$(FLEET_CONF="$T/fleet.conf" "$FC" --projects)" "$(FLEET_CONF="$T/fleet.noconf" "$FC" --projects)"
check "S11 --projects has no directive" "$(FLEET_CONF="$T/fleet.conf" "$FC" --projects | grep -c '@standby')" 0
OUT=$(FLEET_CONF="$T/fleet.noconf" "$FC" --standby); RC=$?
check "S11 no directive rc" "$RC" 0
check "S11 no directive stdout" "$OUT" ""
# Negatives for the parser: the explanatory line, a PARKED row, a short directive.
printf '# Standby directive (#401): "# @standby <box> <hub-name> <hub-id>"\n# PARKED 2026-08-25: project-10 x - - 0 b\n# @standby short-line\n' > "$T/fleet.neg"
check "S11 negatives do not match" "$(FLEET_CONF="$T/fleet.neg" "$FC" --standby)" ""

# ---- S12: smoke through the real renderer ------------------------------------
OUT=$("$SI" box-small --root "$REPO" --cron-file "$CRON" 2>"$T/err"); RC=$?
check "S12 rc" "$RC" 0
[ "$RC" = 0 ] || cat "$T/err"
N=$(printf '%s\n' "$OUT" | grep -c "root ${G}")
[ "$N" -ge 40 ] && ok || bad "S12 want >= 40 gated lines, got $N"
check "S12 no watchdog ping" "$(printf '%s\n' "$OUT" | grep -c 'watchdog-ping')" 0
check "S12 no double prefix" "$(printf '%s\n' "$OUT" | grep -c 'check && .*check && ')" 0
check "S12 renew gated" "$(printf '%s\n' "$OUT" | grep -c "root ${G}/root/harness/bin/hub-lease.sh renew")" 1
printf 'x\n' > "$HARNESS/state/box-id"
"$SI" box-small --root "$REPO" --cron-file "$CRON" >/dev/null 2>"$T/err"; RC=$?
check "S12 own render failure refuses" "$RC" 1

echo "standby-install: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ]
