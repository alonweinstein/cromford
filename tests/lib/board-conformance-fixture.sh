# shellcheck shell=bash
# tests/lib/board-conformance-fixture.sh — the shared scratch harness every
# board-conformance suite runs in (BH-3947). Sourced, never executed. Sources
# tests/lib/scratch.sh, so the caller gets $T and its cleanup trap.
#
#   bc_fixture_setup        (re)build $T/h: fleet.conf with p1 (/api/board),
#                           p2 (/api/feature-board) and gh1 (prefix -), env/p1.env
#                           and env/p2.env, copies of the real scripts, a stub
#                           bin/lane-alert.sh (argv -> $CALLS), a stub
#                           bin/hub-lease.sh, and a stub curl first on PATH.
#   bc_fixture_case <name>  FX=tests/fixtures/board-conformance/<name>.
#
# THE STUB CURL logs its argv, one line per call, to $CURL_LOG. It answers a
# URL from $FX by route: the URL path with the leading / dropped and every
# other / turned into _ (https://p1.example/api/board/tickets -> api_board_tickets).
# $FX/<host>/<route>.code.txt wins over $FX/<route>.code.txt (.txt so the public mirror can audit it), so a case can answer one
# project differently. A missing code file is a 404. The body is <route>.json
# (empty when absent), written to the -o target; the code is printed for -w.
# Siblings add fixture dirs; they do not edit this file.

. "$(dirname "${BASH_SOURCE[0]}")/scratch.sh" || return 1
BC_FX_REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

bc_fixture_case() { FX="$BC_FX_REPO/tests/fixtures/board-conformance/$1"; export FX; }

bc_fixture_setup() {
  local h="$T/h" r="$BC_FX_REPO" f
  [ -e "$h" ] && { scratch_rm "$h" || return 1; }
  export HARNESS="$h" HARNESS_ENV_DIR="$h/env" FLEET_CONF="$h/fleet.conf" \
    BC_NOW=2026-10-03T07:35:00Z CURL_LOG="$T/curl.log" CALLS="$T/calls.log" JOBS_URL=
  unset LANE_GATE_DISABLE BC_TIMEOUT_S
  case ":$PATH:" in *":$T/stub:"*) ;; *) PATH="$T/stub:$PATH"; export PATH ;; esac
  bc_fixture_case base
  mkdir -p "$h/bin/lib/board-conformance" "$h/env" "$h/flags" "$h/logs" "$h/state" "$h/locks" "$T/stub" || return 1
  cat > "$h/fleet.conf" <<'EOF'
# project repo prod board_prefix offset box
p1 org/p1 https://p1.example /api/board 0 hub
p2 org/p2 https://p2.example /api/feature-board 0 hub
gh1 org/gh1 - - 0 hub
EOF
  printf 'P1_API_BASE=https://p1.example\nP1_INTERNAL_API_TOKEN=tok-p1\nMIGRATION_TOKEN=mt-p1\n' > "$h/env/p1.env"
  printf 'P2_API_BASE=https://p2.example\nP2_INTERNAL_API_TOKEN=tok-p2\nMIGRATION_TOKEN=mt-p2\n' > "$h/env/p2.env"
  : > "$h/env/global.env"
  cp "$r/bin/board-conformance.sh" "$r/bin/fleet-conf.sh" "$r/bin/alert_family.py" "$h/bin/" || return 1
  cp "$r"/bin/lib/board-conformance/*.sh "$h/bin/lib/board-conformance/" || return 1
  for f in env-path board-creds internal-token lane-gate alert-state; do
    cp "$r/bin/lib/$f.sh" "$h/bin/lib/" || return 1
  done
  printf '#!/bin/bash\nprintf "%%s\\n" "$*" >> "${CALLS:-/dev/null}"\n' > "$h/bin/lane-alert.sh"
  printf '#!/bin/bash\nexit 0\n' > "$h/bin/hub-lease.sh"
  cat > "$T/stub/curl" <<'EOF'
#!/bin/bash
printf '%s\n' "$*" >> "${CURL_LOG:-/dev/null}"
out=/dev/null; w=""; url=""
while [ $# -gt 0 ]; do
  case "$1" in
    -o) out="$2"; shift ;;
    -w) w="$2"; shift ;;
    -m|-H) shift ;;
    -*) ;;
    *) url="$1" ;;
  esac
  shift
done
rest="${url#*://}"; host="${rest%%/*}"; path="${rest#"$host"}"; path="${path%%\?*}"
route=$(printf '%s' "${path#/}" | tr '/' '_')
src="${FX:-/nonexistent}"; [ -f "$src/$host/$route.code.txt" ] && src="$src/$host"
code=404; [ -f "$src/$route.code.txt" ] && code=$(cat "$src/$route.code.txt")
if [ -f "$src/$route.json" ]; then cat "$src/$route.json" > "$out"; else : > "$out"; fi
[ -n "$w" ] && printf '%s' "$code"
exit 0
EOF
  chmod +x "$h"/bin/*.sh "$T/stub/curl"
  : > "$T/curl.log"; rm -f "$T/calls.log"
}
